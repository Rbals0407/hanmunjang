function normalize(text) {
  return String(text || '').toLowerCase().replace(/\s+/g, '');
}

function shuffle(list) {
  const a = list.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

function idOf(number) {
  return 'q' + String(number).padStart(3, '0');
}

// 1) 고민 유형 판단: 해당하는 유형 이름과, 명언별 유형 점수를 돌려줍니다.
function readWorryTypes(text) {
  const names = [];
  const bonus = {};
  for (const type of WORRY_TYPES) {
    const hits = type['패턴'].filter(p => new RegExp(p).test(text)).length;
    if (hits === 0) continue;
    names.push({ name: type['이름'], hits });
    type['명언'].forEach((number, rank) => {
      // 앞에 적힌 명언일수록 높은 점수(7점에서 시작해 조금씩 줄어듦), 패턴이 여러 개 맞으면 조금 더.
      const point = Math.max(3, 7 - rank * 0.5) + Math.min(hits - 1, 2);
      const id = idOf(number);
      bonus[id] = (bonus[id] || 0) + point;
    });
  }
  names.sort((a, b) => b.hits - a.hits);
  return { names: names.slice(0, 3).map(n => n.name), bonus };
}

// 2) 매칭 키워드 점수. 네 글자 이상 키워드는 사이에 조사가 한 글자 끼어도 맞는 것으로 봅니다.
//    예: 키워드 "공부하기 싫" ↔ 문장 "공부는 하기 싫어"
const looseCache = {};
function keywordHit(word, text) {
  const w = normalize(word);
  if (w.length < 2) return 0;
  if (text.includes(w)) return w.length >= 4 ? 4 : 3;
  if (w.length < 4) return 0;
  if (!looseCache[w]) {
    const escaped = Array.from(w).map(c => c.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'));
    looseCache[w] = new RegExp(escaped.join('.?'));
  }
  return looseCache[w].test(text) ? 2 : 0;
}

function scoreQuote(quote, text, matchedTopics, typeBonus) {
  let score = typeBonus[quote.id] || 0;
  for (const word of quote['키워드']) score += keywordHit(word, text);
  for (const topic of quote['주제']) {
    if (matchedTopics.includes(topic)) score += 2;   // 3) 주제 점수
  }
  return score;
}

// 점수 높은 순서의 후보에서, 관점 유형(행동·생각 전환·위로·경고)이 겹치지 않게 고릅니다.
function pickMixed(candidates, count) {
  const pool = candidates.slice();
  const picked = [];
  const usedTypes = new Set();
  while (picked.length < count && pool.length > 0) {
    let index = pool.findIndex(q => !usedTypes.has(q['관점']));
    if (index === -1) {
      usedTypes.clear();
      index = 0;
    }
    const [q] = pool.splice(index, 1);
    usedTypes.add(q['관점']);
    picked.push(q);
  }
  return picked;
}

async function recommend(worry, quotes, options = {}) {
  const exclude = new Set(options.exclude || []);
  const COUNT = 5;

  // 주제 버튼으로 고른 경우: 그 주제의 명언을 섞어서 고릅니다.
  if (options.topic) {
    const inTopic = shuffle(quotes.filter(q => q['주제'].includes(options.topic) && !exclude.has(q.id)));
    return { items: pickMixed(inTopic, COUNT), weak: false, understood: [] };
  }

  const text = normalize(worry);
  const types = readWorryTypes(text);
  const matchedTopics = TOPICS.filter(t => TOPIC_WORDS[t].some(w => text.includes(normalize(w))));

  const scored = shuffle(quotes)
    .map(q => ({ q, score: scoreQuote(q, text, matchedTopics, types.bonus) }))
    .filter(x => x.score >= 2)
    .sort((a, b) => b.score - a.score);

  // 맞는 명언이 하나도 없으면 "매칭이 약함"으로 알립니다.
  if (scored.length === 0) return { items: [], weak: true, understood: [] };

  // 잘 맞는 후보(최고 점수의 절반 이상) 가운데 위에서 8개 안에서 관점 유형을 섞어 고릅니다.
  const left = scored.filter(x => !exclude.has(x.q.id));
  const cut = scored[0].score * 0.5;
  const strong = left.filter(x => x.score >= cut).slice(0, 8).map(x => x.q);
  const items = pickMixed(strong, COUNT);

  // 5개가 안 되면 나머지 후보에서 점수 순으로 채웁니다.
  if (items.length < COUNT) {
    const rest = left.map(x => x.q).filter(q => !items.includes(q)).slice(0, 12);
    items.push(...pickMixed(rest, COUNT - items.length));
  }

  // 그래도 모자라면 가장 잘 맞은 명언과 같은 주제에서 채웁니다.
  if (items.length < COUNT) {
    const topics = scored[0].q['주제'];
    const same = shuffle(quotes).filter(q =>
      !exclude.has(q.id) && !items.includes(q) && q['주제'].some(t => topics.includes(t)));
    items.push(...pickMixed(same, COUNT - items.length));
  }

  return { items, weak: false, understood: types.names };
}
